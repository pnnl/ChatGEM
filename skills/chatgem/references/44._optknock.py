# Description:
# This script performs an OptKnock-based strain design analysis on the iJN1463 metabolic model
# using COBRApy and the StrainDesign (straindesign) library. The goal is to identify reaction
# knockouts that couple microbial growth with increased succinate production. DO NOT USE CAMEO,
# use SDmodule from this codebase only
#
# The script first loads the SBML model (iJN1463.xml) and configures environmental and
# physiological constraints, including setting the glucose uptake rate and restricting
# several exchange reactions to secretion-only behavior. A list of protected reactions
# (exclusion list) is defined to prevent OptKnock from selecting essential or undesired
# reactions as knockout candidates.
#
# The biomass reaction is set as the primary (inner) objective to represent cellular growth,
# while the succinate exchange reaction (EX_succ_e) is defined as the target (outer) objective
# for production optimization. The wild-type model is optimized to compute baseline growth
# and flux distributions, and a separate optimization is performed to determine the
# theoretical maximum succinate secretion rate without growth constraints.
#
# An OptKnock module is then constructed with a viability constraint that enforces at least
# 10% of the wild-type growth rate. The strain design problem is solved allowing up to two
# reaction knockouts, and only the best solution is retained. Candidate knockout solutions
# are filtered to remove any that contain reactions listed in the exclusion set.
#
# From the valid OptKnock solution, a mutant model is generated by knocking out the selected
# reactions. The mutant strain is simulated under the same conditions as the wild type to
# obtain growth and flux distributions.
#
# The script outputs results to an Excel file (OptKnock_iJN1463_succinate.xlsx) containing:
#  - A summary sheet with wild-type and mutant growth rates, succinate production rates,
#    theoretical maximum succinate yield, and number of knockouts.
#  - A knockouts sheet listing all reactions selected for deletion.
#  - A flux_comparison sheet reporting wild-type and mutant fluxes for each reaction and
#    their differences (mutant minus wild type).
#
# Utility functions are included to interpret knockout indicators returned by StrainDesign,
# and the script automatically selects the first valid OptKnock solution that does not
# violate the exclusion criteria.
#
# Sample ChatGPT prompts to get this code:
# - Python script for OptKnock analysis using COBRApy and StrainDesign.
# - How to perform growth-coupled succinate production optimization in iJN1463.
# - Example of reaction knockout strain design using OptKnock in Python.
# - COBRApy + StrainDesign workflow for mutant construction and flux comparison.
# - Export OptKnock results (WT vs mutant) to Excel using pandas.

import os
import cobra
import straindesign as sd
import pandas as pd
_ASSETS = os.path.join(os.path.dirname(__file__), '..', 'assets')

def is_knockout_value(val):
    if isinstance(val, str):
        return val.strip().upper() in {"KO", "KNOCKOUT", "DEL", "DELETE"}
    try:
        return val < 0
    except Exception:
        return False

def main():
    # ----------------------
    # Load model
    # ----------------------
    model = cobra.io.read_sbml_model(os.path.join(_ASSETS, 'iJN1463.xml'))

    # ----------------------
    # Set glucose uptake
    # ----------------------
    if "EX_glc__D_e" in model.reactions:
        model.reactions.get_by_id("EX_glc__D_e").lower_bound = -6.0

    # ----------------------
    # Set other exchanges to secretion-only
    # ----------------------
    secretion_only = [
        "EX_co2_e",
        "EX_glcn_e",
        "EX_25dkglcn_e",
        "EX_catechol_e",
        "EX_lac__D_e",
        "EX_meoh_e",
        "EX_4oxptn_e",
        "EX_ac_e"
    ]
    for rxn_id in secretion_only:
        if rxn_id in model.reactions:
            r = model.reactions.get_by_id(rxn_id)
            r.lower_bound = 0.0
            r.upper_bound = 1000.0

    # ----------------------
    # Block secretion ONLY (commented out as per your code)
    # ----------------------
    #block_only = ["FUM",
                  #"ATPS4rpp",
                  #"HCO3E",
                  #"H2CO3D"
    #]
    #for rxn_id in block_only:
        #if rxn_id in model.reactions:
            #r = model.reactions.get_by_id(rxn_id)
            #r.lower_bound = 0.0
            #r.upper_bound = 0.0

    # ----------------------
    # EXCLUSION LIST - prevent OptKnock from touching these
    # ----------------------
    excluded_rxns = [
        "ATPM",
        "CAT",
        "CYO1_KT",
        "CYTBO3_4pp",
        "CYTCAA3pp",
        "NADH16pp",
        "NAt3_1p5pp",
        "PItex",
        "PPK"
    ]

    # ----------------------
    # Biomass & target
    # ----------------------
    biomass_rxn = "BIOMASS_KT2440_WT3"
    #biomass_rxn = "BIOMASS_Ecoli_core_w_GAM"
    target_rxn = "EX_succ_e"
    # verify target exists
    if target_rxn not in model.reactions:
        raise ValueError(f"Exchange reaction {target_rxn} not found in the model.")

    # ----------------------
    # Wild-type baseline
    # ----------------------
    model.objective = biomass_rxn
    wt_sol = model.optimize()
    wt_flux = wt_sol.fluxes
    wt_growth = wt_sol.objective_value

    # ----------------------
    # Theoretical max succinate (unconstrained)
    # ----------------------
    succ_model = model.copy()
    succ_model.objective = target_rxn
    theoretical_succ = succ_model.optimize().objective_value

    # ----------------------
    # OptKnock module (allow up to 3 knockouts)
    # ----------------------
    viability_threshold = 0.1 * wt_growth  # 10% WT growth
    optknock_module = sd.SDModule(
        model=model,
        module_type=sd.OPTKNOCK,
        inner_objective=biomass_rxn,
        outer_objective=target_rxn,
        constraints=[f"{biomass_rxn} >= {viability_threshold}"]
    )

    # ----------------------
    # Run OptKnock
    # ----------------------
    max_solutions = 1
    solutions = sd.compute_strain_designs(
        model,
        sd_modules=[optknock_module],
        max_solutions=max_solutions,    # number of solutions solutions
        max_cost=2,                     # number of knockouts knockouts
        solution_approach=sd.BEST
    )

    # ----------------------
    # Loop over solutions, pick first one not containing excluded KOs
    # ----------------------
    ko_list = []
    found_valid = False
    for i in range(max_solutions):
        try:
            reaction_sd = solutions.get_reaction_sd(i)
        except Exception:
            break  # No more solutions
        candidate_ko = []
        skip = False
        for rd in reaction_sd:
            for rxn_id, val in rd.items():
                if is_knockout_value(val):
                    if rxn_id in excluded_rxns:
                        print(f"Solution {i}: Skipped because knockout {rxn_id} is in exclusion list.")
                        skip = True
                    candidate_ko.append(rxn_id)
        if skip:
            continue  # Try next solution
        ko_list = candidate_ko
        found_valid = True
        print(f"Selected solution {i} with knockouts: {ko_list}")
        break  # Only first valid solution

    if not found_valid or not ko_list:
        print("No valid OptKnock solution found (all contain excluded reactions).")
        return

    # ----------------------
    # Build mutant from solution
    # ----------------------
    mutant = model.copy()
    for rxn_id in ko_list:
        if rxn_id in mutant.reactions:
            mutant.reactions.get_by_id(rxn_id).knock_out()

    # ----------------------
    # Mutant simulation
    # ----------------------
    mutant.objective = biomass_rxn
    mut_sol = mutant.optimize()
    mut_flux = mut_sol.fluxes

    # ----------------------
    # Prepare Excel output
    # ----------------------
    wt_df = wt_flux.reset_index()
    wt_df.columns = ["reaction_id", "wt_flux"]
    mut_df = mut_flux.reset_index()
    mut_df.columns = ["reaction_id", "mutant_flux"]
    compare_df = wt_df.merge(mut_df, on="reaction_id", how="outer")
    compare_df["delta(mut-wt)"] = compare_df["mutant_flux"] - compare_df["wt_flux"]
    ko_df = pd.DataFrame({"knockout_reaction_id": ko_list})
    summary_df = pd.DataFrame({
        "metric": [
            "WT_growth",
            "WT_succinate",
            "Mut_growth",
            "Mut_succinate",
            "theoretical_max_succinate",
            "num_KOs"
        ],
        "value": [
            wt_growth,
            wt_flux.get(target_rxn, float("nan")),
            mut_sol.objective_value,
            mut_flux.get(target_rxn, float("nan")),
            theoretical_succ,
            len(ko_list)
        ]
    })
    out_file = "OptKnock_iJN1463_succinate.xlsx"
    with pd.ExcelWriter(out_file, engine="openpyxl") as writer:
        summary_df.to_excel(writer, sheet_name="summary", index=False)
        ko_df.to_excel(writer, sheet_name="knockouts", index=False)
        compare_df.to_excel(writer, sheet_name="flux_comparison", index=False)
    print(f"OptKnock computation complete. Results written to: {out_file}")

if __name__ == "__main__":
    main()